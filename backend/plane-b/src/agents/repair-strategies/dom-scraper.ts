/**
 * DOM Scraper repair strategy — handles Playwright/browser-based collector failures.
 *
 * Diagnoses DOM structure changes (selector breakage, layout shifts) and proposes
 * selector updates or parser rewrites for browser-based collectors.
 */

import type { FailureBundle } from '../../../../shared/types/failure-bundle'
import type { DiagnosticContext, DiagnosticEvidence, RepairAction, RepairProposal, RepairStrategy } from './types'

export class DomScraperRepairStrategy implements RepairStrategy {
  readonly id = 'dom-scraper-repair'
  readonly name = 'DOM Scraper Repair Strategy'
  readonly supportedSources = ['playwright' as const, 'hybrid' as const]
  readonly supportedLayers = ['parse' as const, 'fetch' as const]

  canRepair(bundle: FailureBundle): boolean {
    return (
      this.supportedSources.includes(bundle.fetcherSource as 'playwright' | 'hybrid')
      && (bundle.category === 'dom_change' || bundle.category === 'parse')
    )
  }

  async diagnose(bundle: FailureBundle): Promise<DiagnosticContext> {
    const start = Date.now()
    const evidence: DiagnosticEvidence[] = []
    const suggestedActions: RepairAction[] = []

    // Analyze DOM signature change
    if (bundle.domSignatureHash && bundle.previousDomSignatureHash) {
      evidence.push({
        type: 'dom_signature_change',
        description: `DOM signature changed from ${bundle.previousDomSignatureHash.slice(0, 8)} to ${bundle.domSignatureHash.slice(0, 8)}`,
        data: {
          previous: bundle.previousDomSignatureHash,
          current: bundle.domSignatureHash,
        },
      })
    }

    // Analyze error patterns
    if (bundle.errorType.includes('selector') || bundle.errorMessage.toLowerCase().includes('selector')) {
      evidence.push({
        type: 'selector_failure',
        description: 'Error message indicates CSS selector no longer matches DOM elements',
        data: { errorType: bundle.errorType, errorMessage: bundle.errorMessage },
      })

      suggestedActions.push({
        type: 'selector_update',
        description: `Update CSS selectors in ${bundle.providerId} collector to match current DOM structure`,
        targetFile: `backend/plane-b/src/providers/${bundle.providerId}/parse.ts`,
        estimatedLinesChanged: 10,
        priority: 1,
      })
    }

    // Check for layout/structure changes
    if (bundle.errorMessage.toLowerCase().includes('timeout') && bundle.fetcherSource === 'playwright') {
      evidence.push({
        type: 'page_load_change',
        description: 'Playwright timeout suggests page structure or load behavior changed',
        data: { consecutiveFailures: bundle.consecutiveFailures },
      })

      suggestedActions.push({
        type: 'parser_rewrite',
        description: `Review wait conditions and navigation strategy for ${bundle.providerId}`,
        targetFile: `backend/plane-b/src/providers/${bundle.providerId}/fetch.ts`,
        estimatedLinesChanged: 20,
        priority: 2,
      })
    }

    // Default selector update action if no specific pattern matched
    if (suggestedActions.length === 0) {
      suggestedActions.push({
        type: 'selector_update',
        description: `Regenerate selectors for ${bundle.providerId} based on current DOM snapshot`,
        targetFile: `backend/plane-b/src/providers/${bundle.providerId}/parse.ts`,
        estimatedLinesChanged: 15,
        priority: 1,
      })
    }

    const rootCause = bundle.domSignatureHash !== bundle.previousDomSignatureHash
      ? 'Provider website DOM structure changed, breaking existing CSS selectors'
      : 'DOM parsing failure - possible anti-bot measures or dynamic content change'

    return {
      strategyId: this.id,
      bundleId: bundle.bundleId,
      rootCause,
      rootCauseConfidence: evidence.length > 1 ? 0.8 : 0.5,
      evidence,
      suggestedActions,
      diagnosisMs: Date.now() - start,
    }
  }

  async propose(bundle: FailureBundle, diagnostic: DiagnosticContext): Promise<RepairProposal | null> {
    if (diagnostic.suggestedActions.length === 0) return null

    return {
      strategyId: this.id,
      bundleId: bundle.bundleId,
      diagnostic,
      patches: [], // Patches generated by LLM via tool-gateway at runtime
      requiresReview: true,
      reviewReason: 'DOM selector changes require manual verification against live site structure',
    }
  }
}
