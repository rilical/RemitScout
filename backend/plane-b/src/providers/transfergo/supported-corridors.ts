const uniqPairs = (pairs: Array<[string, string]>) => {
  const map = new Map<string, [string, string]>()
  for (const pair of pairs) {
    map.set(`${pair[0]}:${pair[1]}`, pair)
  }
  return Array.from(map.values())
}

